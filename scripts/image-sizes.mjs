#!/usr/bin/env node
/**
 * Writes src/lib/image-sizes.ts: the pixel size of every picture in public/img, so <img> tags can
 * reserve their space before the file arrives (nothing jumps on a slow pitchside connection).
 * Run after adding or changing pictures:
 *   npm run image-sizes
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pub = join(root, "public");

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

/** [width, height] from the file header, or null for a format we do not read. */
export function sizeOf(buf) {
  // PNG: IHDR is the first chunk
  if (buf.readUInt32BE(0) === 0x89504e47) return [buf.readUInt32BE(16), buf.readUInt32BE(20)];
  // JPEG: walk the segments to the first start-of-frame
  if (buf[0] === 0xff && buf[1] === 0xd8) {
    let i = 2;
    while (i < buf.length - 9) {
      if (buf[i] !== 0xff) {
        i++;
        continue;
      }
      const m = buf[i + 1];
      if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc) {
        return [buf.readUInt16BE(i + 7), buf.readUInt16BE(i + 5)];
      }
      if (m === 0xd8 || m === 0x01 || (m >= 0xd0 && m <= 0xd7) || m === 0xff) {
        i += m === 0xff ? 1 : 2;
        continue;
      }
      i += 2 + buf.readUInt16BE(i + 2);
    }
    return null;
  }
  // WebP: lossy (VP8), lossless (VP8L) or extended (VP8X)
  if (buf.toString("ascii", 0, 4) === "RIFF" && buf.toString("ascii", 8, 12) === "WEBP") {
    const chunk = buf.toString("ascii", 12, 16);
    if (chunk === "VP8 ") return [buf.readUInt16LE(26) & 0x3fff, buf.readUInt16LE(28) & 0x3fff];
    if (chunk === "VP8L") {
      const b = buf.readUInt32LE(21);
      return [(b & 0x3fff) + 1, ((b >> 14) & 0x3fff) + 1];
    }
    if (chunk === "VP8X") return [buf.readUIntLE(24, 3) + 1, buf.readUIntLE(27, 3) + 1];
  }
  // SVG: width/height on the root element, else its viewBox
  const svg = /<svg\b[^>]*>/.exec(buf.toString("utf8", 0, 4096))?.[0];
  if (svg) {
    const attr = (name) => new RegExp(`\\s${name}="([\\d.]+)(px)?"`).exec(svg)?.[1];
    const [w, h] = [attr("width"), attr("height")];
    if (w && h) return [Math.round(+w), Math.round(+h)];
    const box = /viewBox="[\d.-]+[\s,]+[\d.-]+[\s,]+([\d.]+)[\s,]+([\d.]+)"/.exec(svg);
    if (box) return [Math.round(+box[1]), Math.round(+box[2])];
  }
  return null;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const entries = [];
  for (const p of walk(join(pub, "img")).sort()) {
    if (!/\.(png|jpe?g|webp|svg)$/i.test(p)) continue;
    const size = sizeOf(readFileSync(p));
    if (!size) {
      console.warn(`[image-sizes] could not read ${p}`);
      continue;
    }
    entries.push(`  "/${relative(pub, p).split(sep).join("/")}": [${size[0]}, ${size[1]}],`);
  }
  const out = join(root, "src/lib/image-sizes.ts");
  writeFileSync(
    out,
    `// Generated by scripts/image-sizes.mjs — run \`npm run image-sizes\` after adding or changing pictures.\n` +
      `export const IMAGE_SIZES: Record<string, readonly [number, number]> = {\n${entries.join("\n")}\n};\n`,
  );
  console.log(`[image-sizes] ${entries.length} pictures → ${relative(root, out)}`);
}
